let current = (globalThis.navigator?.language ?? 'es').toLowerCase().startsWith('es') ? 'es' : 'en';

export const getLang = () => current;

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'es';
  if (globalThis.document) {
    document.documentElement.lang = current === 'es' ? 'es-AR' : 'en';
    applyTranslations(document);
  }
}

/** Translate a key, replacing {placeholders}. Falls back to Spanish, then the key. */
export function t(key, vars = {}) {
  const str = STRINGS[current][key] ?? STRINGS.es[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

/** Fill every element that has data-i18n="key" (and data-i18n-aria for aria-label). */
export function applyTranslations(root) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
}

